/**
 * Maryland county map for the homepage, from US Census cartographic boundary files (public domain).
 * Re-run when the design or the Census vintage changes:
 *
 *   npm run map:counties
 *
 * - Downloads cb_<year>_us_county_500k.zip into scripts/output/census/ (gitignored) if missing
 * - Keeps Maryland (STATEFP 24: 23 counties and Baltimore City), simplifies it, projects it with
 *   Maryland State Plane parameters (Lambert conformal conic) and writes
 *   src/components/home/maryland-counties.svg: one <path> per county with data-geoid,
 *   data-name and data-label (NAMELSAD, which tells Baltimore County from Baltimore city)
 * - Also writes scripts/output/census/maryland-counties.geojson (unsimplified, lat/lng) for
 *   scripts that need to know which county a point is in
 */
import { execFileSync } from 'child_process';
import { existsSync, readFileSync, statSync, writeFileSync } from 'fs';
import { join } from 'path';

const YEAR = 2023;
const DIR = 'scripts/output/census';
const BASE = `cb_${YEAR}_us_county_500k`;
const ZIP_URL = `https://www2.census.gov/geo/tiger/GENZ${YEAR}/shp/${BASE}.zip`;
const SVG_OUT = 'src/components/home/maryland-counties.svg';
const GEOJSON_OUT = join(DIR, 'maryland-counties.geojson');
const MAX_BYTES = 60 * 1024;

// Maryland State Plane (NAD83) parallels and origin; keeps the state's shape true
const PROJECTION =
  '+proj=lcc +lat_1=38.3 +lat_2=39.45 +lat_0=37.6667 +lon_0=-77 +datum=NAD83 +units=m';

function run(cmd: string, args: string[]) {
  execFileSync(cmd, args, { stdio: ['ignore', 'ignore', 'inherit'] });
}

function main() {
  const shp = join(DIR, `${BASE}.shp`);
  if (!existsSync(shp)) {
    console.log(`Downloading ${ZIP_URL}`);
    run('mkdir', ['-p', DIR]);
    run('curl', ['-sSfL', '-o', join(DIR, 'county.zip'), ZIP_URL]);
    run('unzip', ['-o', '-q', join(DIR, 'county.zip'), '-d', DIR]);
  }

  const filter = ['-i', shp, '-filter', 'STATEFP === "24"'];
  run('npx', ['mapshaper', ...filter, '-o', GEOJSON_OUT, 'format=geojson']);
  run('npx', [
    'mapshaper',
    ...filter,
    '-simplify',
    '10%',
    'weighted',
    'keep-shapes',
    '-proj',
    PROJECTION,
    '-o',
    `${SVG_OUT}.tmp`,
    'format=svg',
    'svg-data=GEOID,NAME,NAMELSAD',
    'width=800',
    'precision=0.1',
  ]);

  // Tidy mapshaper's output: no XML prolog, no fixed size, readable attribute names
  const raw = readFileSync(`${SVG_OUT}.tmp`, 'utf8');
  const svg = raw
    .replace(/<\?xml[^>]*>\s*/, '')
    .replace(/ width="\d+" height="\d+"/, '')
    .replace(/ version="1\.2" baseProfile="tiny"/, '')
    .replace(/<g id="[^"]*">/, '<g>')
    .replace(/data-namelsad=/g, 'data-label=');
  writeFileSync(
    SVG_OUT,
    `<!-- Generated by scripts/generate-county-map.ts from US Census ${BASE} (public domain). Do not edit. -->\n${svg}`
  );
  run('rm', [`${SVG_OUT}.tmp`]);

  const paths = (svg.match(/<path /g) ?? []).length;
  const bytes = statSync(SVG_OUT).size;
  console.log(`${SVG_OUT}: ${paths} counties, ${(bytes / 1024).toFixed(1)} KB`);
  if (paths !== 24)
    throw new Error(`expected 24 Maryland counties, got ${paths}`);
  if (bytes > MAX_BYTES)
    throw new Error(`SVG is over ${MAX_BYTES / 1024} KB; simplify more`);
  console.log(`${GEOJSON_OUT}: unsimplified, for point-in-county lookups`);
}

main();
